import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import { WEEKLY_RECOMMENDATION_LIMIT, getWeeklyRecommendationManifest } from '../src/lib/weekly-recommendations.ts';

const ROOT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MOVIES_DIR = path.join(ROOT_DIR, 'src/data/movies');
const OUTPUT_PATH = path.join(ROOT_DIR, 'src/data/weeklyRecommendations.generated.ts');
const REFERENCE_DATE_VALUE = process.env.WEEKLY_RECOMMENDATIONS_DATE ?? new Date().toISOString().slice(0, 10);

function parseReferenceDate(value) {
	const referenceDate = new Date(`${value}T12:00:00Z`);
	if (Number.isNaN(referenceDate.getTime())) {
		throw new Error(`Fecha inválida para recomendaciones semanales: ${value}`);
	}

	return referenceDate;
}

async function loadMovies() {
	const fileNames = (await readdir(MOVIES_DIR)).filter((fileName) => fileName.endsWith('.json')).sort();
	return Promise.all(
		fileNames.map(async (fileName) => JSON.parse(await readFile(path.join(MOVIES_DIR, fileName), 'utf8'))),
	);
}

function renderGeneratedFile(manifest) {
	return [
		"import type { WeeklyRecommendationManifest } from '../lib/weekly-recommendations';",
		'',
	'// Snapshot generated by scripts/refresh-weekly-recommendations.mjs. Do not edit by hand.',
	'// The homepage computes the current edition at build time from the catalog.',
	`export const WEEKLY_RECOMMENDATIONS_GENERATED_AT = ${JSON.stringify(manifest.generatedAt)};`,
	'',
	`export const WEEKLY_RECOMMENDATIONS: WeeklyRecommendationManifest = ${JSON.stringify(manifest, null, '\t')};`,
	'',
	].join('\n');
}

async function main() {
	const movies = await loadMovies();
	const referenceDate = parseReferenceDate(REFERENCE_DATE_VALUE);
	const manifest = getWeeklyRecommendationManifest(movies, referenceDate, WEEKLY_RECOMMENDATION_LIMIT);

	if (manifest.recommendations.length === 0) {
		throw new Error('No se encontraron películas recomendadas de plataformas para la edición semanal.');
	}

	await writeFile(OUTPUT_PATH, renderGeneratedFile(manifest), 'utf8');
	console.log(
		JSON.stringify(
			{
				generatedAt: manifest.generatedAt,
				weekKey: manifest.weekKey,
				count: manifest.recommendations.length,
				selection: 'stable-weekly-random',
				slugs: manifest.recommendations.map(({ slug }) => slug),
			},
			null,
			2,
		),
	);
}

main().catch((error) => {
	console.error(error);
	process.exit(1);
});
