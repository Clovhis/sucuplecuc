import { writeFile } from 'node:fs/promises';
import { getArgentinaDateKey } from '../src/lib/home-editions.ts';
import { UPCOMING_SOURCE_URL, extractArgentinaReleases, extractYoutubeIds, fetchSource, findEmbeddableTrailer } from './upcoming-release-source.mjs';

const referenceDate = process.env.UPCOMING_RELEASES_DATE ?? getArgentinaDateKey();
const candidates = extractArgentinaReleases(await fetchSource(UPCOMING_SOURCE_URL))
	.filter(({ releaseDate }) => releaseDate > referenceDate).slice(0, 24);
if (candidates.length === 0) throw new Error('The Argentine upcoming-release source returned no future films. The previous edition is unchanged.');

const releases = [];
const failures = [];
for (let start = 0; start < candidates.length && releases.length < 16; start += 3) {
	const batch = await Promise.all(candidates.slice(start, start + 3).map(async ({ sourceId, ...release }) => {
		try {
			const videos = await fetchSource(`https://www.cinesargentinos.com.ar/pelicula/${sourceId}/trailer`);
			const trailer = await findEmbeddableTrailer(extractYoutubeIds(videos));
			if (!trailer) { failures.push({ title: release.title, reason: 'No embeddable YouTube trailer in the Argentine film page' }); return null; }
			console.log(JSON.stringify({ title: release.title, videoTitle: trailer.title, channel: trailer.channel, sourceUrl: release.sourceUrl }));
			return { ...release, slug: `cines-argentinos-${sourceId}`, videoUrl: trailer.videoUrl, thumbnailUrl: `https://i.ytimg.com/vi/${trailer.id}/hqdefault.jpg` };
		} catch (error) { failures.push({ title: release.title, reason: error.message }); return null; }
	}));
	releases.push(...batch.filter(Boolean));
}
if (releases.length < 5) throw new Error(`Only ${releases.length} verified Argentine trailers found; need at least five. The previous edition is unchanged. ${JSON.stringify(failures)}`);
const uniqueReleases = releases.filter((release, index) => releases.findIndex((other) => other.sourceUrl === release.sourceUrl) === index).slice(0, 16);
const output = `// Generated by scripts/update-upcoming-releases.mjs. Builds and movie loads must not refresh this edition.
export interface GeneratedUpcomingRelease {
\tslug: string;
\ttitle: string;
\treleaseDate: string;
\tvideoUrl: string;
\tthumbnailUrl: string;
\tsynopsis?: string;
\tsourceUrl: string;
}
export const GENERATED_UPCOMING_RELEASES_UPDATED_AT = ${JSON.stringify(new Date().toISOString())};
export const GENERATED_UPCOMING_RELEASES: GeneratedUpcomingRelease[] = ${JSON.stringify(uniqueReleases, null, '\t')};
`;
await writeFile(new URL('../src/data/upcomingReleases.generated.ts', import.meta.url), output);
console.log(JSON.stringify({ count: uniqueReleases.length, releases: uniqueReleases.map(({ title, releaseDate, videoUrl, sourceUrl }) => ({ title, releaseDate, videoUrl, sourceUrl })), omitted: failures }, null, 2));
